function normalizeLanguage(language) {
  if (!language) return null;
  const primary = language.toLowerCase().split(/[-_]/)[0];
  return supportedLanguages.includes(primary) ? primary : null;
}

function getSavedLanguage() {
  try {
    return normalizeLanguage(window.localStorage.getItem(languageStorageKey));
  } catch {
    return null;
  }
}

function detectBrowserLanguage() {
  const candidates = [...(navigator.languages || []), navigator.language];
  return candidates.map(normalizeLanguage).find(Boolean) || "en";
}

function t(key) {
  return translations[activeLanguage][key] || translations.en[key] || key;
}

